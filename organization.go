var (
	// ErrInvalidInput rejects invalid configuration or bounded request syntax.
	ErrInvalidInput = errors.New("organization: invalid input")
	// ErrForbidden deliberately conflates absence, inactive authority and denial.
	ErrForbidden = errors.New("organization: forbidden")
	// ErrConflict rejects duplicate or stale optimistic transitions.
	ErrConflict = errors.New("organization: conflict")
	// ErrLastOwner denies removal or demotion of the final recovery-capable owner.
	ErrLastOwner = errors.New("organization: last owner")
	// ErrLimit denies a configured organization or membership cardinality limit.
	ErrLimit = errors.New("organization: limit exceeded")
	// ErrUnavailable redacts dependency, invalid-output and panic diagnostics.
	ErrUnavailable = errors.New("organization: unavailable")
	// ErrSensitiveSerialization prevents implicit export of runtime custody.
	ErrSensitiveSerialization = errors.New("organization: sensitive serialization forbidden")
)

// ID preserves a canonical organization identifier, including existing ULIDs.
// It carries neither ownership nor membership authority. IDs are case-sensitive.
type ID string

// Role is a closed static role. Unknown values never grant permissions.
type Role string

const (
	RoleOwner         Role = "owner"
	RoleAdministrator Role = "administrator"
	RoleMember        Role = "member"
)

// Descriptor identifies the one versioned storage-neutral mutation schema.
// Unknown and read operations return zero, which identity rejects.
func (o Operation) Descriptor() identity.FeatureOperation {
	if teamMutation(o) {
		return identity.FeatureOperation{Owner: "organization", OperationID: string(o), SchemaID: "organization-team", SchemaVersion: 1, RecordRequirement: identity.FeatureRecordRequired}
	}
	if o != Create && o != Update && o != AddMember && o != UpdateMember && o != RemoveMember && o != LeaveMember && o != OwnerTransfer {
		return invitationDescriptor(o)
	}
	return identity.FeatureOperation{Owner: "organization", OperationID: string(o), SchemaID: "organization-membership", SchemaVersion: 1, RecordRequirement: identity.FeatureRecordRequired}
}

func (r Role) Valid() bool { return r == RoleOwner || r == RoleAdministrator || r == RoleMember }

// Organization is one immutable primary snapshot, not an access decision.
// Version is also the organization policy/authority epoch in this profile.
type Organization struct {
	ID         ID
	TenantID   identity.TenantID
	Slug, Name string
	Version    uint64
	Active     bool
}

// Member is a tenant/organization-bound membership snapshot. Removed bindings
// retain their version and organization-scoped authorization epoch as tombstones.
// Neither Role nor this structural value authenticates its human user.
type Member struct {
	OrganizationID                ID
	TenantID                      identity.TenantID
	UserID                        identity.UserID
	Role                          Role
	Version, AuthorizationVersion uint64
	Active                        bool
}

// Operation is the canonical callable operation, never selected from free text.
type Operation string

const (
	Create       Operation = "identity.organization.create"
	Update       Operation = "identity.organization.update"
	AddMember    Operation = "identity.organization.member.add"
	UpdateMember Operation = "identity.organization.member.update"
	RemoveMember Operation = "identity.organization.member.remove"
	LeaveMember  Operation = "identity.organization.member.leave"
	Get          Operation = "identity.organization.get"
	ListMembers  Operation = "identity.organization.member.list"
)

// Authentication selects only explicit bearer transport. Cookie/CSRF workflows
// require the session owner's native browser composition and are not emulated.
type Authentication struct {
	TenantID identity.TenantID
	Bearer   authentication.BearerCredential
}

func (Authentication) Format(s fmt.State, _ rune) {
	_, _ = io.WriteString(s, "organization.Authentication(redacted)")
}
func (Authentication) MarshalJSON() ([]byte, error) { return nil, ErrSensitiveSerialization }
func (Authentication) MarshalText() ([]byte, error) { return nil, ErrSensitiveSerialization }

// Query is a bounded primary read generated by Service after authentication.
// Adapters must recheck membership on each call; there is no positive cache.
// TargetID is used only for native identity-owner reads when preparing mutation.
type Query struct {
	Operation      Operation
	TenantID       identity.TenantID
	ActorID        identity.UserID
	OrganizationID ID
	TargetID       identity.UserID
	Cursor         identity.UserID
	Limit          uint32
	TeamID         ID
	TeamCursor     string
}

// View is an independently owned primary snapshot. OwnerCount includes active
// owners only; it is advisory until rechecked under the mutation's aggregate lock.
type View struct {
	Organization   Organization
	Actor, Target  Member
	TargetUser     identity.User
	OwnerCount     uint64
	Members        []Member
	NextCursor     identity.UserID
	Team           Team
	TeamMember     TeamMember
	Teams          []Team
	TeamMembers    []TeamMember
	NextTeamCursor string
}

// Repository reads only authoritative owned organization state and delegates
// target identity reads to identity's native owner. It owns no authentication
// engine. Implementations must honor deadlines and safely support concurrency.
type Repository interface {
	Read(context.Context, Query) (View, error)
}

// UnitOfWork is invocation-scoped, storage-neutral mutation/recovery authority.
// The native adapter binds it immutably to one original command and current
// admitted caller. Recover must reject any other ID, never perform global lookup
// or replay effects, and preserve committed/not-committed/unknown distinctions.
type UnitOfWork interface {
	Execute(context.Context, Command) (StoreResult, error)
	Recover(context.Context, identity.CommandID) (StoreResult, error)
}

// StoreResult retains the existing identity-owned outcome protocol. A committed
// result is historical, not current membership, a fresh grant or a new session.
// Unknown must be reconciled using the same command; never allocate a retry ID.
type StoreResult struct {
	Receipt        identity.CommandResult
	OrganizationID ID
	MemberID       identity.UserID
	// InvitationID is set only for invitation commands, including unknown
	// outcomes. It identifies the original command, never a delivery claim.
	InvitationID ID
}

// Config is explicit immutable policy. Limits are finite and enforced again by
// the durable adapter under its own locks. MaxMembers follows the reference
// organization.max_members range; MaxPerUser follows organization.max_per_user.
// MaximumPerTenant is an additional deployment-selected cap, not a reference
// default. Canonical validation preserves, rather than transforms, supplied IDs.
type Config struct {
	Clock                                            clock.Clock
	MaximumDuration                                  time.Duration
	PolicyID                                         string
	PolicyVersion                                    uint64
	MaximumMembers, MaximumPerUser, MaximumPerTenant uint64
	ValidateCanonicalID                              func(context.Context, ID) error
	Teams                                            TeamConfig
	// OwnerTransferAudience explicitly selects the signed primary-proof audience.
	// Empty disables ownership transfer; it is independent of session audience.
	OwnerTransferAudience string
}

// Service owns bounded authentication and pure policy/preparation, not durable
// transactions. A native adapter supplies the scoped UnitOfWork to Execute.
// NewService retains borrowed immutable collaborators and starts no goroutines.
type Service struct {
	sessions   *session.SessionService
	repository Repository
	policy     authorization.Service
	config     Config
}

func NewService(sessions *session.SessionService, repository Repository, policy authorization.Service, c Config) (*Service, error) {
	if sessions == nil || nilValue(repository) || nilValue(policy) || nilValue(c.Clock) || c.MaximumDuration <= 0 || c.MaximumDuration > 5*time.Second || !safeID(c.PolicyID) || c.PolicyVersion == 0 || c.MaximumMembers < 1 || c.MaximumMembers > 100000 || c.MaximumPerUser < 1 || c.MaximumPerUser > 1000 || c.MaximumPerTenant < 1 || c.MaximumPerTenant > 1000000 || c.ValidateCanonicalID == nil || c.Teams.Validate() != nil || c.OwnerTransferAudience != "" && !validOwnerTransferAudience(c.OwnerTransferAudience) {
		return nil, ErrInvalidInput
	}
	c.PolicyID = strings.Clone(c.PolicyID)
	c.OwnerTransferAudience = strings.Clone(c.OwnerTransferAudience)
	return &Service{sessions: sessions, repository: repository, policy: policy, config: c}, nil
}

// CreateRequest preallocates the canonical ID and preserves CommandID across
// retries. Slugs are lowercase ASCII labels of 1..63 bytes, unique per tenant;
// names are 1..256 UTF-8 bytes without control characters. They are never logs.
type CreateRequest struct {
	Authentication            Authentication
	CommandID                 identity.CommandID
	ID                        ID
	Slug, Name, CorrelationID string
}

// UpdateRequest replaces only Name and Slug using CreateRequest's bounds and
// case-sensitive semantics; it neither clears nor accepts other metadata.
// OrganizationVersion is the exact current organization/policy epoch. Owners
// and administrators may update; identical metadata returns ErrConflict without
// a transition, new epoch, audit or lifecycle event. Preserve CommandID across
// retries and reconcile ambiguous outcomes using the native adapter's recovery.
type UpdateRequest struct {
	Authentication            Authentication
	CommandID                 identity.CommandID
	OrganizationID            ID
	OrganizationVersion       uint64
	Name, Slug, CorrelationID string
}

// MemberRequest binds an exact target and organization/member optimistic versions.
// Add requires Role and preserves an existing removed membership's version (zero
// only for a never-admitted user). Remove requires the active member's version;
// it never treats arbitrary absence as successful removal.
// Update requires a different valid static Role and the exact active membership
// version. Only owners may grant owner or change an owner; at least one owner
// (the static profile's recovery administrator) must survive every transition.
type MemberRequest struct {
	Authentication                     Authentication
	CommandID                          identity.CommandID
	OrganizationID                     ID
	UserID                             identity.UserID
	Role                               Role
	OrganizationVersion, MemberVersion uint64
	CorrelationID                      string
}

// LeaveRequest removes only the authenticated human's current membership in
// the explicitly selected organization. OrganizationVersion is its exact policy
// epoch; the current membership version is captured during preparation, never
// supplied as a target override. The final recovery-capable owner cannot leave.
// Keep CommandID across retries. Historical recovery still requires current
// membership; a retained receipt is not permission to read after leaving.
type LeaveRequest struct {
	Authentication      Authentication
	CommandID           identity.CommandID
	OrganizationID      ID
	OrganizationVersion uint64
	CorrelationID       string
}

// ReadRequest chooses an exact organization. Cursor is an exclusive UserID in
// bytewise database C collation; Limit must be 1..100 for member listing.
type ReadRequest struct {
	Authentication Authentication
	OrganizationID ID
	Cursor         identity.UserID
	Limit          uint32
	CorrelationID  string
}

// CommandInput is the trusted adapter projection of a Service-issued command.
// It contains original private session admission and bearer custody: do not log,
// persist or automatically serialize it. Adapters map every field into the sole
// durable owner's keyed command; none alone grants mutation permission.
type CommandInput struct {
	Binding                                          identity.CommandBinding
	Operation                                        Operation
	Organization                                     Organization
	Actor, Target                                    Member
	TargetUser                                       identity.User
	Role                                             Role
	Session                                          session.GetResult
	Bearer                                           authentication.BearerCredential
	MaximumMembers, MaximumPerUser, MaximumPerTenant uint64
	Invitation                                       InvitationInput
	Team                                             Team
	TeamMember                                       TeamMember
	Teams                                            TeamConfig
	OwnerTransferProof                               authentication.ReauthenticationProof
}

type commandState struct {
	owner *Service
	input CommandInput
}

// Command is immutable Service-issued preparation, not a transaction/receipt.
// Zero is invalid. Only a native adapter's public service composes Execute with
// its own invocation-scoped UnitOfWork; applications need no workflow glue.
type Command struct{ state *commandState }

func (c Command) Input() (CommandInput, error) {
	if c.state == nil {
		return CommandInput{}, ErrInvalidInput
	}
	return c.state.input, nil
}
func (Command) Format(s fmt.State, _ rune) {
	_, _ = io.WriteString(s, "organization.Command(redacted)")
}
func (Command) MarshalJSON() ([]byte, error) { return nil, ErrSensitiveSerialization }
func (Command) MarshalText() ([]byte, error) { return nil, ErrSensitiveSerialization }
func (CommandInput) Format(s fmt.State, _ rune) {
	_, _ = io.WriteString(s, "organization.CommandInput(redacted)")
}
func (CommandInput) MarshalJSON() ([]byte, error) { return nil, ErrSensitiveSerialization }
func (CommandInput) MarshalText() ([]byte, error) { return nil, ErrSensitiveSerialization }

func (s *Service) PrepareCreate(ctx context.Context, r CreateRequest) (out Command, err error) {
	defer func() {
		if recover() != nil {
			out, err = Command{}, ErrUnavailable
		}
	}()
	if s == nil || ctx == nil || !validSlug(r.Slug) || !boundedText(r.Name, 256) || !safeID(string(r.ID)) || !safeID(r.CorrelationID) {
		return out, ErrInvalidInput
	}
	if _, err = identity.ParseCommandID(string(r.CommandID)); err != nil {
		return out, ErrInvalidInput
	}
	bounded, cancel := context.WithTimeout(ctx, s.config.MaximumDuration)
	defer cancel()
	if err = s.config.ValidateCanonicalID(bounded, r.ID); err != nil {
		return out, ErrInvalidInput
	}
	observed, actor, err := s.authenticate(bounded, r.Authentication)
	if err != nil {
		return out, err
	}
	if err = s.authorize(bounded, actor, r.Authentication.TenantID, r.ID, 0, Create, r.CorrelationID); err != nil {
		return out, err
	}
	org := Organization{ID: r.ID, TenantID: r.Authentication.TenantID, Name: strings.Clone(r.Name), Slug: strings.Clone(r.Slug), Active: true}
	return s.command(r.CommandID, Create, r.CorrelationID, observed, r.Authentication.Bearer, org, Member{}, Member{}, identity.User{ID: actor, TenantID: r.Authentication.TenantID}, RoleOwner), nil
}

func (s *Service) PrepareAddMember(ctx context.Context, r MemberRequest) (Command, error) {
	return s.prepareMember(ctx, r, AddMember)
}

// PrepareUpdateMember freezes one exact active membership's static role change.
// Current owners and administrators may change nonowners; only owners may grant
// or demote owners. Preparation writes nothing. The native owner must serialize
// the last-owner invariant with removal, leave and ownership transfer and advance
// both organization policy and the changed subject's scoped authority atomically.
func (s *Service) PrepareUpdateMember(ctx context.Context, r MemberRequest) (Command, error) {
	return s.prepareMember(ctx, r, UpdateMember)
}

// PrepareUpdate authenticates the human actor and checks current organization
// membership and action policy. Preparation writes nothing; the native adapter
// must recheck current authority and the expected version under its own locks.
func (s *Service) PrepareUpdate(ctx context.Context, r UpdateRequest) (out Command, err error) {
	defer func() {
		if recover() != nil {
			out, err = Command{}, ErrUnavailable
		}
	}()
	if s == nil || ctx == nil || !safeID(string(r.OrganizationID)) || !safeID(r.CorrelationID) || !boundedText(r.Name, 256) || !validSlug(r.Slug) || r.OrganizationVersion == 0 || r.OrganizationVersion == ^uint64(0) {
		return out, ErrInvalidInput
	}
	if _, err = identity.ParseCommandID(string(r.CommandID)); err != nil {
		return out, ErrInvalidInput
	}
	bounded, cancel := context.WithTimeout(ctx, s.config.MaximumDuration)
	defer cancel()
	if err = s.config.ValidateCanonicalID(bounded, r.OrganizationID); err != nil {
		return out, ErrInvalidInput
	}
	observed, actor, err := s.authenticate(bounded, r.Authentication)
	if err != nil {
		return out, err
	}
	v, err := s.repository.Read(bounded, Query{Operation: Update, TenantID: r.Authentication.TenantID, ActorID: actor, OrganizationID: r.OrganizationID})
	if err != nil {
		return out, publicError(bounded, err)
	}
	if !validView(v, r.Authentication.TenantID, r.OrganizationID, actor) || v.Actor.Role != RoleOwner && v.Actor.Role != RoleAdministrator {
		return out, ErrForbidden
	}
	if err = s.authorize(bounded, actor, r.Authentication.TenantID, r.OrganizationID, v.Organization.Version, Update, r.CorrelationID); err != nil {
		return out, err
	}
	if err = bounded.Err(); err != nil {
		return out, err
	}
	if observed.ValidateAt(s.config.Clock.Now()) != nil {
		return out, ErrForbidden
	}
	if v.Organization.Version != r.OrganizationVersion || v.Organization.Name == r.Name && v.Organization.Slug == r.Slug {
		return out, ErrConflict
	}
	v.Organization.Name, v.Organization.Slug = strings.Clone(r.Name), strings.Clone(r.Slug)
	return s.command(r.CommandID, Update, r.CorrelationID, observed, r.Authentication.Bearer, v.Organization, v.Actor, Member{}, identity.User{ID: actor, TenantID: r.Authentication.TenantID}, ""), nil
}
func (s *Service) PrepareRemoveMember(ctx context.Context, r MemberRequest) (Command, error) {
	return s.prepareMember(ctx, r, RemoveMember)
}

// PrepareLeaveMember authenticates self, checks current membership/action policy
// and freezes its exact membership snapshot without writing. Durable adapters
// must fence that same actor and the final owner under the shared aggregate lock.
func (s *Service) PrepareLeaveMember(ctx context.Context, r LeaveRequest) (Command, error) {
	return s.prepareMember(ctx, MemberRequest{Authentication: r.Authentication, CommandID: r.CommandID, OrganizationID: r.OrganizationID, OrganizationVersion: r.OrganizationVersion, CorrelationID: r.CorrelationID}, LeaveMember)
}

func (s *Service) prepareMember(ctx context.Context, r MemberRequest, op Operation) (out Command, err error) {
	defer func() {
		if recover() != nil {
			out, err = Command{}, ErrUnavailable
		}
	}()
	if s == nil || ctx == nil || !safeID(string(r.OrganizationID)) || op != LeaveMember && !safeID(string(r.UserID)) || !safeID(r.CorrelationID) || r.OrganizationVersion == 0 || r.OrganizationVersion == ^uint64(0) || (op == AddMember || op == UpdateMember) && !r.Role.Valid() || op == RemoveMember && (r.Role != "" || r.MemberVersion == 0) || op == UpdateMember && (r.MemberVersion == 0 || r.MemberVersion == ^uint64(0)) {
		return out, ErrInvalidInput
	}
	if _, err = identity.ParseCommandID(string(r.CommandID)); err != nil {
		return out, ErrInvalidInput
	}
	bounded, cancel := context.WithTimeout(ctx, s.config.MaximumDuration)
	defer cancel()
	if err = s.config.ValidateCanonicalID(bounded, r.OrganizationID); err != nil {
		return out, ErrInvalidInput
	}
	observed, actor, err := s.authenticate(bounded, r.Authentication)
	if err != nil {
		return out, err
	}
	if op == LeaveMember {
		r.UserID = actor
	}
	v, err := s.repository.Read(bounded, Query{Operation: op, TenantID: r.Authentication.TenantID, ActorID: actor, OrganizationID: r.OrganizationID, TargetID: r.UserID})
	if err != nil {
		return out, publicError(bounded, err)
	}
	if !validView(v, r.Authentication.TenantID, r.OrganizationID, actor) || op != LeaveMember && v.Actor.Role == RoleMember || op == LeaveMember && v.Target != v.Actor {
		return out, ErrForbidden
	}
	if err = s.authorize(bounded, actor, r.Authentication.TenantID, r.OrganizationID, v.Organization.Version, op, r.CorrelationID); err != nil {
		return out, err
	}
	if op == LeaveMember || op == UpdateMember {
		if err = bounded.Err(); err != nil {
			return out, err
		}
		if observed.ValidateAt(s.config.Clock.Now()) != nil {
			return out, ErrForbidden
		}
		if op == LeaveMember {
			r.MemberVersion = v.Actor.Version
		}
	}
	if v.Organization.Version != r.OrganizationVersion || v.Target.Version != r.MemberVersion {
		return out, ErrConflict
	}
	if v.TargetUser.Validate(r.Authentication.TenantID) != nil || v.TargetUser.ID != r.UserID || (op == AddMember || op == LeaveMember || op == UpdateMember) && v.TargetUser.Status != identity.StatusActive {
		return out, ErrForbidden
	}
	if op == AddMember {
		if v.Target.Active {
			return out, ErrConflict
		}
		if r.Role == RoleOwner && v.Actor.Role != RoleOwner {
			return out, ErrForbidden
		}
	} else {
		if !v.Target.Active || v.Target.UserID != r.UserID || v.Target.OrganizationID != r.OrganizationID || v.Target.TenantID != r.Authentication.TenantID {
			return out, ErrForbidden
		}
		if v.Target.Role == RoleOwner && v.Actor.Role != RoleOwner {
			return out, ErrForbidden
		}
		if op == UpdateMember {
			if !v.Target.Role.Valid() || v.Target.AuthorizationVersion == 0 || r.Role == RoleOwner && v.Actor.Role != RoleOwner {
				return out, ErrForbidden
			}
			if v.Target.Role == r.Role {
				return out, ErrConflict
			}
		}
		if v.Target.Role == RoleOwner && v.OwnerCount < 2 && (op != UpdateMember || r.Role != RoleOwner) {
			return out, ErrLastOwner
		}
	}
	return s.command(r.CommandID, op, r.CorrelationID, observed, r.Authentication.Bearer, v.Organization, v.Actor, v.Target, v.TargetUser, r.Role), nil
}

func (s *Service) command(id identity.CommandID, op Operation, correlation string, observed session.GetResult, bearer authentication.BearerCredential, org Organization, actor, target Member, user identity.User, role Role) Command {
	spec, _ := observed.Session.Bindings()
	b := identity.CommandBinding{CommandID: id, TenantID: org.TenantID, UserID: user.ID, ActorID: identity.ActorID(spec.UserID), ActorKind: authorization.SubjectUser, OperationID: string(op), PolicyID: s.config.PolicyID, PolicyVersion: s.config.PolicyVersion, SchemaID: "organization-membership", SchemaVersion: 1, CorrelationID: strings.Clone(correlation), RecordID: string(org.ID)}
	return Command{state: &commandState{owner: s, input: CommandInput{Binding: b, Operation: op, Organization: org, Actor: actor, Target: target, TargetUser: user, Role: role, Session: observed, Bearer: bearer, MaximumMembers: s.config.MaximumMembers, MaximumPerUser: s.config.MaximumPerUser, MaximumPerTenant: s.config.MaximumPerTenant}}}
}

// Execute repeats current action policy with the original Service custody
// before borrowing the adapter's one-command work. Policy callbacks run before
// protected SQL; later lock waits require native final admission.
// It never retries an unknown result or replaces its command identity.
func (s *Service) Execute(ctx context.Context, c Command, work UnitOfWork) (out StoreResult, err error) {
	attempted := false
	uncertain := func() StoreResult {
		x := c.state.input
		return StoreResult{OrganizationID: x.Organization.ID, MemberID: x.TargetUser.ID, InvitationID: x.Invitation.Record.ID, Receipt: identity.CommandResult{Binding: x.Binding, Outcome: identity.CommitOutcomeUnknown, Feature: &identity.FeatureReceipt{Operation: x.Operation.Descriptor()}}}
	}
	defer func() {
		if recover() != nil {
			if attempted {
				out = uncertain()
				err = identity.UnknownCommitError{CommandID: c.state.input.Binding.CommandID}
			} else {
				err = ErrUnavailable
			}
		}
	}()
	if s == nil || ctx == nil || c.state == nil || c.state.owner != s || nilValue(work) {
		return out, ErrInvalidInput
	}
	now := s.config.Clock.Now()
	if c.state.input.Session.ValidateAt(now) != nil || (c.state.input.Operation == InvitationAccept || c.state.input.Operation == InvitationCancel || c.state.input.Operation == InvitationReject || c.state.input.Operation == InvitationResend) && !now.Before(c.state.input.Invitation.Record.ExpiresAt) {
		return out, ErrForbidden
	}
	bounded, cancel := context.WithTimeout(ctx, s.config.MaximumDuration)
	defer cancel()
	if err := bounded.Err(); err != nil {
		return out, err
	}
	x := c.state.input
	if x.Operation == OwnerTransfer && !s.validOwnerTransferProof(x.Session, x.OwnerTransferProof, s.config.Clock.Now()) {
		return out, ErrForbidden
	}
	if err := s.authorize(bounded, identity.UserID(x.Binding.ActorID), x.Binding.TenantID, x.Organization.ID, x.Organization.Version, x.Operation, x.Binding.CorrelationID); err != nil {
		return out, err
	}
	// An external decision is not a lease: it cannot renew the session owner's
	// original evidence interval or the invitation's exclusive deadline.
	now = s.config.Clock.Now()
	if err := bounded.Err(); err != nil {
		return out, err
	}
	if x.Session.ValidateAt(now) != nil || (x.Operation == InvitationAccept || x.Operation == InvitationCancel || x.Operation == InvitationReject || x.Operation == InvitationResend) && !now.Before(x.Invitation.Record.ExpiresAt) {
		return out, ErrForbidden
	}
	if x.Operation == OwnerTransfer && !s.validOwnerTransferProof(x.Session, x.OwnerTransferProof, now) {
		return out, ErrForbidden
	}
	attempted = true
	out, err = work.Execute(bounded, c)
	before := x.Organization.Version
	if x.Operation == InvitationSend || x.Operation == InvitationAccept || x.Operation == InvitationCancel || x.Operation == InvitationReject || x.Operation == InvitationExpire || x.Operation == InvitationResend {
		// The sole native receipt describes its invitation aggregate. Acceptance
		// also creates a membership, but must not relabel that second event or
		// unrelated organization policy epoch as the invitation transition.
		before = x.Invitation.Record.Version
	}
	if out.Receipt.Outcome != identity.CommitOutcomeInvalid && (out.Receipt.Validate() != nil || out.Receipt.Binding != x.Binding || out.Receipt.Feature == nil || out.Receipt.Feature.Operation != x.Operation.Descriptor() || out.OrganizationID != x.Organization.ID || out.MemberID != x.TargetUser.ID || out.InvitationID != x.Invitation.Record.ID || out.Receipt.Outcome == identity.CommitOutcomeCommitted && (out.Receipt.Feature.BeforeVersion != before || out.Receipt.Feature.AfterVersion != before+1)) {
		return uncertain(), ErrUnavailable
	}
	if out.Receipt.Outcome == identity.CommitOutcomeInvalid && err == nil {
		return uncertain(), ErrUnavailable
	}
	return out, publicError(bounded, err)
}

